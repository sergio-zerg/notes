-- Tighten the schema created by 001.

-- content was declared nullable while the domain rejects an empty note, so the
-- column could hold a state the application refuses to produce. Existing NULLs
-- are collapsed to the empty string, which the domain also rejects, so no
-- invalid row survives the constraint.
UPDATE notes SET content = '' WHERE content IS NULL;
ALTER TABLE notes ALTER COLUMN content SET NOT NULL;

-- SERIAL leaves an ordinary sequence and a column default behind, which the
-- next explicit INSERT ... OVERRIDING SYSTEM VALUE has to undo by hand.
-- An identity column is declared by the table itself, so a caller can no longer
-- set id without opting in to it.
ALTER TABLE notes ALTER COLUMN id DROP DEFAULT;
DROP SEQUENCE IF EXISTS notes_id_seq;
ALTER TABLE notes ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
-- Restart above the highest id in use: the fresh identity sequence starts at 1
-- and would collide with rows written before this migration.
SELECT setval(pg_get_serial_sequence('notes', 'id'),
              COALESCE((SELECT MAX(id) FROM notes), 1),
              EXISTS (SELECT 1 FROM notes));

-- The list endpoint pages with ORDER BY id, which the primary key already
-- serves; an extra index on the same column in the other direction would only
-- cost write throughput.

