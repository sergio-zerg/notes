ALTER TABLE notes ALTER COLUMN id DROP IDENTITY;
CREATE SEQUENCE notes_id_seq OWNED BY notes.id;
ALTER TABLE notes ALTER COLUMN id SET DEFAULT nextval('notes_id_seq');
SELECT setval('notes_id_seq', COALESCE((SELECT MAX(id) FROM notes), 1), false);

